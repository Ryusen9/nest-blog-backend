import { ApiProperty, ApiPropertyOptional, ApiSchema } from '@nestjs/swagger';

@ApiSchema({
  description:
    'TypeORM update result. `affected` is 0 when no row matches the id.',
})
export class UpdateResultDto {
  @ApiProperty({
    type: 'array',
    items: { type: 'object', additionalProperties: true },
    example: [],
    description: 'Rows generated by the database, if any.',
  })
  generatedMaps: Record<string, unknown>[];

  @ApiProperty({
    description: 'Driver-specific raw result.',
    example: [],
  })
  raw: unknown;

  @ApiPropertyOptional({
    example: 1,
    nullable: true,
    description: 'Number of rows updated.',
  })
  affected?: number | null;
}

@ApiSchema({
  description:
    'TypeORM delete result. `affected` is 0 when no row matches the id.',
})
export class DeleteResultDto {
  @ApiProperty({
    description: 'Driver-specific raw result.',
    example: [],
  })
  raw: unknown;

  @ApiPropertyOptional({
    example: 1,
    nullable: true,
    description: 'Number of rows deleted.',
  })
  affected?: number | null;
}
